import { access, readFile, writeFile } from 'fs/promises';

const pkgUrl = new URL('../package.json', import.meta.url);
const outputUrl = new URL('../../core/types/model/schema-version.js', import.meta.url);
const releaseOutputUrl = new URL('../../core/types/model/release-version.js', import.meta.url);
const cliReleaseOutputUrl = new URL('../lib/release-version.js', import.meta.url);
const corePkgUrl = new URL('../../core/package.json', import.meta.url);
const runtimePkgUrl = new URL('../../runtime/package.json', import.meta.url);
const runtimeReleaseOutputUrl = new URL('../../runtime/shared/release-version.js', import.meta.url);

const pkgText = await readFile(pkgUrl, 'utf8');
const pkg = JSON.parse(pkgText);
const schemaVersion = pkg.schemaVersion;
const corePkg = JSON.parse(await readFile(corePkgUrl, 'utf8'));
const runtimePkg = JSON.parse(await readFile(runtimePkgUrl, 'utf8'));

if (typeof schemaVersion !== 'string' || !schemaVersion.length) {
  throw new Error('cli/package.json must declare a non-empty schemaVersion');
}

const contextUrl = new URL(`../context/${schemaVersion}/`, import.meta.url);
const requiredContextFiles = [
  'blu.schema.json',
  'blu.annex.md',
  'viz.schema.json',
  'sys.schema.json',
  'protocol.schema.json',
  'prf.schema.json',
  'capabilities.schema.json',
  'agents.v1.json',
  'model-test.schema.json',
  'test-report.schema.json'
];

await Promise.all(requiredContextFiles.map((file) => access(new URL(file, contextUrl))));

const schemaMetadata = [
  {
    file: 'agents.v1.json',
    id: 'https://vmblu.dev/schemas/agents.v1.json',
    title: 'vmblu agent configuration'
  },
  {
    file: 'model-test.schema.json',
    id: `https://vmblu.dev/context/${schemaVersion}/model-test.schema.json`,
    title: 'vmblu Model Test'
  },
  {
    file: 'blu.schema.json',
    id: `https://vmblu.dev/context/${schemaVersion}/blu.schema.json`,
    title: `vmblu Blueprint Model (v${schemaVersion})`
  },
  {
    file: 'viz.schema.json',
    id: `https://vmblu.dev/context/${schemaVersion}/viz.schema.json`,
    title: `vmblu Visual Model (v${schemaVersion})`
  },
  {
    file: 'prf.schema.json',
    id: `https://vmblu.dev/context/${schemaVersion}/prf.schema.json`
  },
  {
    file: 'sys.schema.json',
    id: `https://vmblu.dev/context/${schemaVersion}/sys.schema.json`,
    title: `vmblu System Configuration (v${schemaVersion})`
  },
  {
    file: 'protocol.schema.json',
    id: `https://vmblu.dev/context/${schemaVersion}/protocol.schema.json`,
    title: `vmblu Protocol Definition (v${schemaVersion})`
  },
  {
    file: 'test-report.schema.json',
    id: `https://vmblu.dev/context/${schemaVersion}/test-report.schema.json`,
    title: 'vmblu Test Report'
  }
];

for (const expected of schemaMetadata) {
  const schema = JSON.parse(await readFile(new URL(expected.file, contextUrl), 'utf8'));
  if (schema.$id !== expected.id || (expected.title && schema.title !== expected.title)) {
    throw new Error(
      `Context ${schemaVersion} metadata in ${expected.file} does not match cli/package.json schemaVersion`
    );
  }
}

const content = `// Auto-generated by cli/scripts/generate-schema-version.js\n` +
  `export const SCHEMA_VERSION = ${JSON.stringify(schemaVersion)};\n`;

await writeFile(outputUrl, content, 'utf8');

const releaseContent = `// Auto-generated by cli/scripts/generate-schema-version.js\n` +
  `export const CORE_VERSION = ${JSON.stringify(corePkg.version)};\n` +
  `export const SCHEMA_VERSION = ${JSON.stringify(schemaVersion)};\n`;

await writeFile(releaseOutputUrl, releaseContent, 'utf8');

const cliReleaseContent = `// Auto-generated by cli/scripts/generate-schema-version.js\n` +
  `export const CLI_VERSION = ${JSON.stringify(pkg.version)};\n` +
  `export const SCHEMA_VERSION = ${JSON.stringify(schemaVersion)};\n`;

await writeFile(cliReleaseOutputUrl, cliReleaseContent, 'utf8');

const runtimeReleaseContent = `// Auto-generated by cli/scripts/generate-schema-version.js\n` +
  `export const RUNTIME_VERSION = ${JSON.stringify(runtimePkg.version)};\n\n` +
  `export function runtimeCompatibilityFamily(version = RUNTIME_VERSION) {\n` +
  `    const match = String(version ?? '').match(/^(\\d+)\\.(\\d+)\\.(\\d+)(?:[-+].*)?$/)\n` +
  `    if (!match) throw new Error(\`Invalid vmblu runtime version: \${version}\`)\n` +
  `    return \`\${match[1]}.\${match[2]}\`\n` +
  `}\n\n` +
  `export function assertRuntimeCompatibility(expectedFamily) {\n` +
  `    if (!expectedFamily) return runtimeCompatibilityFamily()\n` +
  `    const actualFamily = runtimeCompatibilityFamily()\n` +
  `    if (expectedFamily !== actualFamily) {\n` +
  `        throw new Error(\`Incompatible vmblu runtime \${RUNTIME_VERSION}; generated application requires compatibility family \${expectedFamily}\`)\n` +
  `    }\n` +
  `    return actualFamily\n` +
  `}\n`;

await writeFile(runtimeReleaseOutputUrl, runtimeReleaseContent, 'utf8');
